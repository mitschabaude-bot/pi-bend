 result=header+f'# {len(runs)} property runs; exact membership for {len(emoji())} RGI emoji.\n'+property_nodes+'\ndef properties(+code: U32) -> U32:\n  '+property_root+'\n\ndef emojiHash(text: String,value: U32) -> U32:\n  match text:\n    case SNil{}: value\n    case SCon{char,rest}: emojiHash(rest,U32.mul(U32.xor(value,Char.to_u32(char)),16777619))\n\n'+emoji_nodes+'\ndef emojiCandidates(+hash: U32,+text: String) -> Bool:\n  '+emoji_root+'\n\ndef rgiTail(+char: Char,rest: String) -> Bool:\n  match rest:\n    case SNil{}: U32.is_ne(U32.and(properties(Char.to_u32(char)),64),0)\n    case +rest: Bool.pick(Unit -> Bool,U32.is_ne(U32.and(properties(Char.to_u32(char)),128),0),_ => emojiCandidates(emojiHash(SCon{char,rest},2166136261),SCon{char,rest}),_ => False{})(Unit{})\ndef isRgiEmoji(text: String) -> Bool:\n  match text:\n    case SNil{}: False{}\n    case SCon{char,rest}: rgiTail(char,rest)\n'
 return result
