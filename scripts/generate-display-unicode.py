def source(name):
 folder,digest=SOURCES[name];path=ROOT/'build/unicode-17-display'/name
 if not path.exists():
  path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(urlopen('https://www.unicode.org/Public/17.0.0/'+folder+name,timeout=30).read())
 raw=path.read_bytes();assert hashlib.sha256(raw).hexdigest()==digest,name
 return raw.decode()
def rows(name):
 for line in source(name).splitlines():
  line=line.split('#')[0].strip()
  if line:yield [x.strip() for x in line.split(';')]
def span(text):
 values=text.split('..');return range(int(values[0],16),int(values[-1],16)+1)
def emoji():
 result=set()
 for name in ['emoji-sequences.txt','emoji-zwj-sequences.txt']:
  for row in rows(name):
   if '..' in row[0]:result.update((cp,) for cp in span(row[0]))
   else:result.add(tuple(int(cp,16) for cp in row[0].split()))
 return result
def properties():
 values=[0]*0x110000;first=None
 for row in rows('UnicodeData.txt'):
  cp=int(row[0],16);category=row[2]
  if row[1].endswith(', First>'):first=cp;continue
  lo=first if row[1].endswith(', Last>') else cp;first=None
  flags=(1 if category.startswith('M') else 0)|(2 if category=='Mc' else 0)|(4 if category in ('Cc','Cs') else 0)|(8 if category=='Cf' else 0)|(1024 if category.startswith('P') else 0)
  values[lo:cp+1]=[flags]*(cp-lo+1)
 for row in rows('DerivedCoreProperties.txt'):
  if row[1]=='Default_Ignorable_Code_Point':
   for cp in span(row[0]):values[cp]|=16
 for row in rows('EastAsianWidth.txt'):
  if row[1] in ('W','F'):
   for cp in span(row[0]):values[cp]|=32
 for row in rows('Scripts.txt'):
  if row[1] in ('Han','Hiragana','Katakana','Hangul','Bopomofo'):
   for cp in span(row[0]):values[cp]|=256
 for row in rows('ScriptExtensions.txt'):
  selected=bool(set(row[1].split()) & {'Hani','Hira','Kana','Hang','Bopo'})
  for cp in span(row[0]):values[cp]=(values[cp]&~256)|(256 if selected else 0)
 for sequence in emoji():
  values[sequence[0]]|=64 if len(sequence)==1 else 128
 # Only punctuation within the CJK break scripts is kept (bit 512).
 values=[(v&~1024)|(512 if v&1024 and v&256 else 0) for v in values]
 return values
def hash_sequence(points):
 h=2166136261
 for cp in points:h=((h^cp)*16777619)&0xffffffff
 return h
def literal(points):return '"'+''.join('\\u{'+format(cp,'x')+'}' for cp in points)+'"'
